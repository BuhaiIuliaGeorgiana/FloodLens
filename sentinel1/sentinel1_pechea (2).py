COLLECTION = "COPERNICUS/S1_GRD"
EVENT_SLUG = "pechea-2024-09"


def find_scenes(bbox=BBOX, windows=None):
    """Return metadata dictionaries; date ends are exclusive.

    Coverage is an approximate valid VV+VH pixel fraction at 100 m,
    useful for screening, not an accuracy/confidence score.
    """
    windows = WINDOWS if windows is None else windows
    aoi = ee.Geometry.Rectangle(bbox, proj="EPSG:4326", geodesic=False)
    base = (ee.ImageCollection(COLLECTION).filterBounds(aoi)
            .filter(ee.Filter.eq("instrumentMode", "IW"))
            .filter(ee.Filter.eq("resolution_meters", 10))
            .filter(ee.Filter.listContains("transmitterReceiverPolarisation", "VV"))
            .filter(ee.Filter.listContains("transmitterReceiverPolarisation", "VH")))

    def record(image):
        valid = image.select(["VV", "VH"]).mask().reduce(ee.Reducer.min())
        coverage = valid.unmask(0, False).reduceRegion(
            reducer=ee.Reducer.mean(), geometry=aoi, scale=100,
            maxPixels=1000000).values().get(0)
        return image.set("record", ee.Dictionary({
            "asset_id": ee.String(COLLECTION).cat("/").cat(ee.String(image.get("system:index"))),
            "acquired_at": image.date().format("yyyy-MM-dd'T'HH:mm:ss'Z'", "UTC"),
            "pass": image.get("orbitProperties_pass"),
            "relative_orbit": image.get("relativeOrbitNumber_start"),
            "platform": image.get("platform_number"),
            "coverage_fraction_approx": coverage,
            "pixel_spacing_m": 10,
            "bands": ["VV", "VH"],
            "units": "dB",
        }))

    records = []
    for period, (start, end) in windows.items():
        items = (base.filterDate(start, end).sort("system:time_start")
                 .map(record).aggregate_array("record").getInfo())
        records.extend(dict(item, period=period) for item in items)
    return records


def download(url, path, signature):
    """Validate the response before replacing a local export."""
    response = requests.get(url, timeout=180)
    response.raise_for_status()
    if not response.content.startswith(signature):
        raise ValueError(f"Unexpected file format for {path.name}")
    path.write_bytes(response.content)


def export_scenes(records, output_dir="export/sentinel1_all",
                  bbox=BBOX, export_geotiff=False):
    """Download stable PNGs, metadata and optional quantitative GeoTIFFs.

    PNGs use EPSG:3857 to align with the app's Leaflet map projection.
    All scenes use identical display limits per band. No cloud filter is needed.
    """
    root = Path(output_dir)
    folder = root / "data" / "pechea"
    folder.mkdir(parents=True, exist_ok=True)
    aoi = ee.Geometry.Rectangle(bbox, proj="EPSG:4326", geodesic=False)
    manifest = []

    for item in records:
        image = ee.Image(item["asset_id"]).select(["VV", "VH"]).clip(aoi)
        scene_id = item["asset_id"].rsplit("/", 1)[-1]
        stem = f"s1_{item['period']}_{scene_id}"
        for band, limits in {"VV": (-25, 0), "VH": (-30, -5)}.items():
            filename = f"{stem}_{band.lower()}.png"
            url = image.select(band).getThumbURL({
                "min": limits[0], "max": limits[1],
                "palette": ["000000", "ffffff"],
                "region": aoi, "crs": "EPSG:3857",
                "dimensions": 1400, "format": "png",
            })
            download(url, folder / filename, b"\x89PNG\r\n\x1a\n")
            manifest.append({
                "id": f"{stem}_{band.lower()}",
                "source": "Sentinel-1",
                "period": item["period"],
                "type": "image",
                "url": f"/data/pechea/{filename}",
                "bounds": list(bbox),
                "acquired_at_utc": item["acquired_at"],
                "status": "available",
            })
            print("Downloaded", filename)

        if export_geotiff:
            # Small AOI: below the EE direct download size limit.
            url = image.toFloat().getDownloadURL({
                "region": aoi, "scale": 10, "crs": "EPSG:32635",
                "format": "ZIPPED_GEO_TIFF", "filePerBand": False,
            })
            download(url, root / f"{stem}_db_geotiff.zip", b"PK")

    # Keep provenance separate so the frontend contract remains exact.
    (root / "candidates.json").write_text(json.dumps(records, indent=2))
    (root / "layers_sentinel1.json").write_text(json.dumps(manifest, indent=2))
    print("Saved metadata to", root)
    return manifest


def get_sentinel1_layers(output_dir="export/sentinel1_all", bbox=BBOX,
                        export_geotiff=False):
    """Return two image records per matching scene, across all three windows.

    Includes every matching IW 10 m VV+VH scene intersecting the AOI,
    regardless of pass/orbit/platform or partial coverage. No selection,
    mosaicking, date averaging or flood classification is performed.
    Empty searches return []; download errors raise rather than marking
    missing files as available. Orbit metadata stays in candidates.json.
    """
    records = find_scenes(bbox=bbox)
    return export_scenes(records, output_dir, bbox, export_geotiff)

